"""Render an AgentBlueprint into an installable Python package, and test it before publishing.

Everything is written inside agent/ of the agent repository (ForgeOne's rule):

    agent/pyproject.toml          installable: pip install ./agent  ->  the `<name>` command
    agent/<pkg>/blueprint.yaml    the agent itself: plan, prompts, tools, criteria (written by the builder)
    agent/<pkg>/agent.py          loads the blueprint into forgeone.agentkit.Agent
    agent/<pkg>/__main__.py       the command: <name> run "..." | check | info
    agent/tests/test_<pkg>.py     smoke tests, no model calls
    agent/spec.yaml               the browse steps' AgentSpec, so `forgeone run` and the evals keep working
    agent/README.md

The code around the blueprint is fixed templates: the builder designs the agent, the framework
runs it, and the package is the same, reviewable shape for every agent.
"""
from __future__ import annotations

import json
import os
import py_compile
import re
import subprocess
import sys
import tempfile
import tomllib
from pathlib import Path

import yaml

from ..agentkit.blueprint import AgentBlueprint

DEFAULT_FORGEONE = "https://github.com/jonamvanuden/forgeone"


def package_name(agent: str) -> str:
    pkg = re.sub(r"[^a-z0-9_]", "_", agent.lower()).strip("_") or "agent"
    return pkg if pkg[0].isalpha() else f"agent_{pkg}"


def forgeone_requirement() -> str:
    """The exact ForgeOne the agent was built and tested against: this checkout's commit."""
    if os.getenv("FORGEONE_PACKAGE_REQUIREMENT"):
        return os.environ["FORGEONE_PACKAGE_REQUIREMENT"]
    from ..config import settings
    from ..workspace import git as g

    home = settings().home
    web = g.github_web_url(g.remote_url(home)) if (home / ".git").exists() else None
    sha = g.git(home, "rev-parse", "HEAD", check=False) if (home / ".git").exists() else ""
    return f"forgeone @ git+{web or DEFAULT_FORGEONE}.git@{sha or 'main'}"


def render_package(bp: AgentBlueprint, requirement: str) -> dict[str, str]:
    pkg, name = package_name(bp.name), bp.name
    titles = [m.title for m in bp.milestones]
    files = {
        "agent/pyproject.toml": f"""[build-system]
requires = ["setuptools>=68"]
build-backend = "setuptools.build_meta"

[project]
name = {json.dumps(name)}
version = "0.1.0+{bp.version()}"
description = {json.dumps(" ".join(bp.description.split()))}
requires-python = ">=3.11"
dependencies = [{json.dumps(requirement)}]

[project.scripts]
{name} = "{pkg}.__main__:main"

[tool.setuptools.packages.find]
include = ["{pkg}*"]

[tool.setuptools.package-data]
{pkg} = ["blueprint.yaml"]
""",
        f"agent/{pkg}/__init__.py": f'"""{name}: built by ForgeOne on forgeone.agentkit. See README.md."""\n',
        f"agent/{pkg}/agent.py": f'''"""{name}, generated by ForgeOne. The agent is blueprint.yaml; this file only loads it.

Do not edit by hand: change goal.md or evals/ and let ForgeOne rebuild it.
"""
from pathlib import Path

from forgeone.agentkit import Agent

AGENT = Agent.from_file(Path(__file__).with_name("blueprint.yaml"))
''',
        f"agent/{pkg}/__main__.py": f'''"""The `{name}` command: run "...", check, info."""
from forgeone.agentkit import run_cli

from .agent import AGENT


def main() -> None:
    run_cli(AGENT)


if __name__ == "__main__":
    main()
''',
        f"agent/{pkg}/blueprint.yaml": bp.to_yaml(),
        f"agent/tests/test_{pkg}.py": f'''"""Smoke tests generated by ForgeOne: the blueprint is valid and its plan builds. No model calls."""
from forgeone.agentkit import check
from forgeone.work.model import Goal

from {pkg}.agent import AGENT


def test_blueprint_passes_the_framework_checks():
    assert check(AGENT) == []


def test_every_command_follows_the_blueprint_plan():
    plan = AGENT.plan(Goal(title="t", description="Who refined sugar first?", playbook=AGENT.playbook.name,
                           playbook_args={{"model": "claude-haiku-5-5"}}))
    assert [m.title for m in plan] == {titles!r}
    steps = [t.step for m in plan for t in m.tasks]
    assert steps.count("agentkit.report") == 1 and "agentkit.browse" in steps
    assert all("verify" in t.stages for m in plan for t in m.tasks)
''',
        "agent/spec.yaml": yaml.safe_dump(bp.spec().model_dump(), sort_keys=False, allow_unicode=True),
        "agent/README.md": _readme(bp, pkg),
    }
    return files


def _readme(bp: AgentBlueprint, pkg: str) -> str:
    plan = "\n".join(f"{i}. **{m.title}**: " + "; ".join(f"`{t.kind}` {t.title}" for t in m.tasks)
                     for i, m in enumerate(bp.milestones, 1))
    return f"""# {bp.name}

{bp.description}

Built by ForgeOne on `forgeone.agentkit`: every command runs as a goal with milestones and tasks,
each task verified, every attempt logged in the same store as ForgeOne (see the Control Room).

## Use
```bash
python3 -m venv .venv && .venv/bin/pip install ./agent
.venv/bin/{bp.name} check                     # blueprint and plan are valid, no model calls
.venv/bin/{bp.name} run "your research command" --budget 0.50
.venv/bin/{bp.name} run "..." --json          # the contract ForgeOne evaluates against
```
Settings come from `.env` in the working directory: `ANTHROPIC_API_KEY`, `DATABASE_URL`,
`BRAVE_API_KEY` (web search), `FORGEONE_AGENT_MODEL`.

## The plan every command follows
{plan}

Version `{bp.version()}`. The agent is `{pkg}/blueprint.yaml`; do not edit it by hand.
"""


# ------------------------------------------------------------------ testing before publishing
def _run(args: list[str], cwd: Path, env_path: Path, timeout: int = 120) -> tuple[bool, str]:
    env = {**os.environ, "PYTHONPATH": os.pathsep.join([str(env_path), os.environ.get("PYTHONPATH", "")]).rstrip(os.pathsep),
           "PYTHONDONTWRITEBYTECODE": "1"}
    try:
        p = subprocess.run(args, cwd=cwd, env=env, capture_output=True, text=True, timeout=timeout)
    except subprocess.TimeoutExpired:
        return False, f"timed out after {timeout} s"
    out = (p.stdout + p.stderr).strip()
    return p.returncode == 0, out[-1500:]


TEST_RUNNER = r'''
import importlib.util, sys, traceback
path = sys.argv[1]
spec = importlib.util.spec_from_file_location("generated_tests", path)
mod = importlib.util.module_from_spec(spec)
spec.loader.exec_module(mod)
failed = 0
names = [n for n in dir(mod) if n.startswith("test_") and callable(getattr(mod, n))]
for n in names:
    try:
        getattr(mod, n)()
        print("ok  ", n)
    except Exception:
        failed += 1
        print("FAIL", n)
        traceback.print_exc()
print(f"{len(names) - failed} of {len(names)} tests passed")
sys.exit(1 if failed or not names else 0)
'''


def test_package(files: dict[str, str], workdir: Path | None = None) -> list[dict]:
    """Write the package to a temporary folder and test it like a user would: it compiles, it
    imports with this ForgeOne, the framework check passes, its own tests pass. All checks are hard."""
    tmp = Path(workdir) if workdir else Path(tempfile.mkdtemp(prefix="forgeone-package-"))
    for rel, text in files.items():
        p = tmp / rel
        p.parent.mkdir(parents=True, exist_ok=True)
        p.write_text(text, encoding="utf-8")
    agent_dir = tmp / "agent"
    checks: list[dict] = []

    try:
        meta = tomllib.loads(files["agent/pyproject.toml"])
        scripts = meta["project"].get("scripts", {})
        ok, detail = bool(scripts), f"name {meta['project']['name']}, command {', '.join(scripts)}"
    except Exception as e:  # noqa: BLE001
        ok, detail = False, f"{type(e).__name__}: {e}"
    checks.append({"name": "pyproject_is_valid", "hard": True, "passed": ok, "detail": detail})

    bad = []
    for rel in files:
        if rel.endswith(".py"):
            try:
                py_compile.compile(str(tmp / rel), doraise=True, cfile=os.devnull)
            except py_compile.PyCompileError as e:
                bad.append(f"{rel}: {e.msg}")
    checks.append({"name": "python_compiles", "hard": True, "passed": not bad,
                   "detail": "; ".join(bad) or "every .py file compiles"})

    pkg = next(Path(r).parts[1] for r in files if r.endswith("/agent.py"))
    probe = (f"import sys\nfrom {pkg}.agent import AGENT\nfrom forgeone.agentkit import check\n"
             "p = check(AGENT)\nprint(AGENT.name, AGENT.version, 'OK' if not p else 'FAILED')\n"
             "print('\\n'.join(p))\nsys.exit(1 if p else 0)\n")
    ok, out = _run([sys.executable, "-c", probe], agent_dir, agent_dir)
    checks.append({"name": "imports_and_passes_framework_check", "hard": True, "passed": ok, "detail": out or "no output",
                   "fix": "Fix the blueprint so that `<agent> check` passes."})

    tests = [r for r in files if r.startswith("agent/tests/") and r.endswith(".py")]
    results = []
    for rel in tests:
        ok, out = _run([sys.executable, "-c", TEST_RUNNER, str(tmp / rel)], agent_dir, agent_dir)
        results.append((ok, f"{rel}: {out}"))
    checks.append({"name": "generated_tests_pass", "hard": True, "passed": bool(results) and all(r[0] for r in results),
                   "detail": "\n".join(r[1] for r in results) or "no tests were generated"})
    return checks
